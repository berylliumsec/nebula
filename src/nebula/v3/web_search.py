"""Public-web research through a loopback metasearch runtime owned by this host.

Nebula holds no search account and no API key. A pinned SearXNG container runs
on loopback, and ``web.search`` asks it for ranked public results. The queries
still reach upstream engines, so the tool declares ``cloud_transfer`` and a
``local_only`` project denies it outright.

This is research, never reconnaissance. The runtime cannot reach an engagement
target, results are bounded and redacted before they enter model context, and
no tool can retrieve a result URL: ``browser.navigate`` stays scope-checked, so
a link from here is reachable only when it is already an authorized target.
"""

