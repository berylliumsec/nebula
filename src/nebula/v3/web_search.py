SETTINGS_ID = "web-search"
CONTAINER_NAME = "nebula-search"
SOURCE_REFERENCE = "docker.io/searxng/searxng:latest"
EXPECTED_REPOSITORY = "docker.io/searxng/searxng"
CONTAINER_PORT = 8080
PORT_RANGE = (24_800, 24_899)

MAX_RESULTS = 10
DEFAULT_RESULTS = 5
MAX_QUERY_CHARS = 256
MAX_SNIPPET_CHARS = 300
MAX_TITLE_CHARS = 200
SEARCH_TIMEOUT_SECONDS = 12.0
READY_TIMEOUT_SECONDS = 90.0
PULL_TIMEOUT_SECONDS = 900
IDLE_STOP_SECONDS = 900.0

Freshness = Literal["any", "day", "week", "month", "year"]
_TIME_RANGE = {"day": "day", "week": "week", "month": "month", "year": "year"}

# Hosts an engagement might legitimately own that are never worth treating as a
# scope disclosure: a query cannot avoid naming the public suffix itself.
_DISCLOSURE_MIN_LABEL_CHARS = 4


class WebSearchError(RuntimeError):
    """The search runtime could not answer; the operator can act on the reason."""


class SearchRuntimeUnavailable(WebSearchError):
    """No container runtime is configured, so the local runtime cannot run."""


class WebSearchResult(NebulaModel):
    rank: int = Field(ge=1, le=MAX_RESULTS)
    title: str = Field(max_length=MAX_TITLE_CHARS)
    url: str = Field(max_length=500)
    snippet: str = Field(default="", max_length=MAX_SNIPPET_CHARS)
    engine: str | None = Field(default=None, max_length=40)
    published_at: str | None = Field(default=None, max_length=40)


def load_settings(store: NebulaStore) -> WebSearchSettings | None:
    try:
        return store.get(WebSearchSettings, SETTINGS_ID)
    except NotFoundError as exc:  # diagnostic-expected: absent until first use
        record_caught_exception(
            "runtime",
            "runtime.web_search.settings_absent",
            "The web search settings entity has not been created yet.",
            exc,
            stage="web_search",
        )
        return None


def web_search_enabled(scope: ScopePolicy) -> bool:
    # local_only forbids any egress, and every search leaves this host.
    return scope.web_search and not scope.local_only


def settings_document(
    engines: Sequence[WebSearchEngine], *, secret_key: str, port: int
) -> str:
    """Render the runtime's settings.yml.

    The stock image ships without the JSON API and with the bot limiter on,
    both of which would reject Nebula's own requests, so neither default is
    left in place.
    """

    enabled = "\n".join(
        f"  - name: {engine.value}\n    disabled: false" for engine in engines
    )
    return f"""# Generated by Nebula. Edits are replaced when the runtime restarts.
use_default_settings: true
general:
  instance_name: "Nebula research"
  donation_url: false
  privacypolicy_url: false
  contact_url: false
  enable_metrics: false
server:
  secret_key: "{secret_key}"
  bind_address: "0.0.0.0"
  port: {CONTAINER_PORT}
  base_url: "http://127.0.0.1:{port}/"
  limiter: false
  public_instance: false
  image_proxy: false
  method: "GET"
search:
  safe_search: 0
  autocomplete: ""
  default_lang: "en"
  formats:
    - json
outgoing:
  request_timeout: 6.0
  max_request_timeout: 10.0
  pool_connections: 20
  pool_maxsize: 10
ui:
  infinite_scroll: false
  static_use_hash: true
engines:
{enabled}
"""


def _free_port() -> int:
    for candidate in range(PORT_RANGE[0], PORT_RANGE[1] + 1):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
            probe.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
            try:
                probe.bind(("127.0.0.1", candidate))
            except OSError:  # diagnostic-expected: a busy port is expected here
                continue
            return candidate
    raise WebSearchError(
        f"no free loopback port in {PORT_RANGE[0]}-{PORT_RANGE[1]} for the "
        "search runtime"
    )


def _normalized_repository(value: str) -> str:
    reference = value.strip().lower()
    if reference.startswith("docker.io/"):
        return reference
    if "/" not in reference or "." not in reference.split("/", 1)[0]:
        return f"docker.io/{reference}"
    return reference


class SearchRuntime:
    """Own the lifecycle of the loopback metasearch container.

    The container is published to 127.0.0.1 only. Binding it to every
    interface would hand anyone on the LAN an open web proxy, which matters
    because Core is routinely reachable from phones on the same network.
    """

    def __init__(
        self,
        *,
        store: NebulaStore,
        data_root: Path,
        platform: str = "linux/amd64",
    ) -> None:
        self.store = store
        self.config_root = data_root / "search"
        self.platform = platform
        self._lock = asyncio.Lock()
        self._idle_task: asyncio.Task[None] | None = None
        self._last_used = 0.0

    # -- runner resolution -------------------------------------------------

    def _profile(self) -> StoredRunnerProfile:
        profiles = [
            profile
            for profile in self.store.list_entities(StoredRunnerProfile, limit=1_000)
            if profile.enabled and profile.healthy
        ]
        local = next((profile for profile in profiles if profile.id == "local"), None)
        if local is not None:
            return local
        if len(profiles) == 1:
            return profiles[0]
        if not profiles:
            raise SearchRuntimeUnavailable(
                "web search needs an enabled, verified container runtime; "
                "configure one in Settings > Runtimes"
            )
        raise SearchRuntimeUnavailable(
            "the container runtime for web search is ambiguous; name the "
            "preferred runner profile 'local'"
        )

    def _runtime_argv(self, profile: StoredRunnerProfile) -> list[str]:
        argv = [profile.executable]
        is_docker = profile.runtime.value == ContainerRuntimeType.DOCKER.value
        if profile.socket:
            argv.extend(["--host" if is_docker else "--url", profile.socket])
        elif profile.context:
            argv.extend(["--context" if is_docker else "--connection", profile.context])
        return argv

    async def _run(
        self, profile: StoredRunnerProfile, *arguments: str, timeout: int = 60
    ) -> tuple[str, str, int]:
        process = await asyncio.create_subprocess_exec(
            *self._runtime_argv(profile),
            *arguments,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
            stdin=asyncio.subprocess.DEVNULL,
            env=_runtime_environment(),
        )
        try:
            stdout, stderr = await asyncio.wait_for(
                process.communicate(), timeout=timeout
            )
        except asyncio.TimeoutError:
            process.kill()
            await process.wait()
            raise WebSearchError(
                f"the container runtime did not answer within {timeout}s"
            ) from None
        return (
            stdout.decode("utf-8", "replace"),
            stderr.decode("utf-8", "replace"),
            process.returncode or 0,
        )

    # -- image -------------------------------------------------------------

    async def install(self) -> str:
        """Pull the image and pin it by the digest the runtime proves."""

        profile = self._profile()
        _, stderr, code = await self._run(
            profile, "pull", SOURCE_REFERENCE, timeout=PULL_TIMEOUT_SECONDS
        )
        if code != 0:
            raise WebSearchError(f"search image pull failed: {stderr.strip()[:500]}")
        return await self._verified_digest(profile)

    async def _verified_digest(self, profile: StoredRunnerProfile) -> str:
        stdout, stderr, code = await self._run(
            profile,
            "image",
            "inspect",
            SOURCE_REFERENCE,
            "--format",
            "{{json .}}",
            timeout=30,
        )
        if code != 0:
            raise WebSearchError(
                f"search image could not be inspected: {stderr.strip()[:500]}"
            )
        try:
            document = json.loads(stdout)
        except json.JSONDecodeError as exc:
            record_caught_exception(
                "runtime",
                "runtime.web_search.inspect_invalid_json",
                "The container runtime returned invalid image inspection JSON.",
                exc,
                stage="web_search",
            )
            raise WebSearchError("image inspection returned invalid JSON") from exc
        if isinstance(document, list):
            document = document[0] if document else {}
        digests: list[str] = []
        for value in document.get("RepoDigests") or document.get("repoDigests") or []:
            if not isinstance(value, str) or "@sha256:" not in value:
                continue
            repository, digest = value.rsplit("@", 1)
            if _normalized_repository(repository) == EXPECTED_REPOSITORY:
                digests.append(digest)
        pinned = sorted(
            {item for item in digests if re.fullmatch(r"sha256:[0-9a-f]{64}", item)}
        )
        if not pinned:
            raise WebSearchError(
                "the runtime did not prove the search image belongs to the "
                f"official {EXPECTED_REPOSITORY} repository"
            )
        return pinned[0]

    # -- container ---------------------------------------------------------

    def _write_configuration(
        self, engines: Sequence[WebSearchEngine], port: int
    ) -> Path:
        self.config_root.mkdir(parents=True, exist_ok=True)
        self.config_root.chmod(0o700)
        path = self.config_root / "settings.yml"
        secret_path = self.config_root / "secret"
        if secret_path.exists():
            secret_key = secret_path.read_text(encoding="utf-8").strip()
        else:
            secret_key = secrets.token_hex(32)
            secret_path.write_text(secret_key, encoding="utf-8")
            secret_path.chmod(0o600)
        path.write_text(
            settings_document(engines, secret_key=secret_key, port=port),
            encoding="utf-8",
        )
        path.chmod(0o600)
        return path

    def _run_argv(self, *, image: str, port: int, configuration: Path) -> list[str]:
        return [
            "run",
            "--detach",
            f"--name={CONTAINER_NAME}",
            "--pull=never",
            "--cap-drop=ALL",
            "--security-opt=no-new-privileges",
            "--cpus=1",
            "--memory=512m",
            "--pids-limit=256",
            "--tmpfs=/tmp:rw,noexec,nosuid,nodev,size=64m",
            # Loopback only. Never 0.0.0.0: Core is reachable over the LAN and
            # an exposed metasearch instance is an open proxy.
            f"--publish=127.0.0.1:{port}:{CONTAINER_PORT}",
            "--env=SEARXNG_SETTINGS_PATH=/etc/searxng/settings.yml",
            f"--volume={configuration}:/etc/searxng/settings.yml:ro",
            image,
        ]

    async def state(self) -> tuple[WebSearchRuntimeState, str]:
        try:
            profile = self._profile()
        except SearchRuntimeUnavailable as exc:
            # diagnostic-expected: an unconfigured runtime is a reportable state
            return WebSearchRuntimeState.ABSENT, str(exc)
        stdout, _, code = await self._run(
            profile,
            "container",
            "inspect",
            CONTAINER_NAME,
            "--format",
            "{{.State.Running}}",
            timeout=20,
        )
        if code != 0:
            return WebSearchRuntimeState.ABSENT, "the search runtime is not created"
        running = stdout.strip().lower() == "true"
        if not running:
            return WebSearchRuntimeState.STOPPED, "the search runtime is stopped"
        return WebSearchRuntimeState.READY, "the search runtime is running"

    async def ensure_ready(self) -> int:
        """Start the runtime if needed and return its loopback port."""

        async with self._lock:
            settings = load_settings(self.store)
            engines = settings.engines if settings else list(WebSearchEngine)[:3]
            port = settings.port if settings and settings.port else _free_port()
            digest = settings.image_digest if settings else None
            profile = self._profile()

            state, _ = await self.state()
            if state == WebSearchRuntimeState.READY and await self._probe(port):
                self._touch()
                return port

            if state in {WebSearchRuntimeState.STOPPED, WebSearchRuntimeState.READY}:
                await self._run(profile, "rm", "--force", CONTAINER_NAME, timeout=30)

            if digest is None:
                digest = await self.install()
            image = f"{EXPECTED_REPOSITORY}@{digest}"
            configuration = self._write_configuration(engines, port)
            _, stderr, code = await self._run(
                profile,
                *self._run_argv(image=image, port=port, configuration=configuration),
                timeout=120,
            )
            if code != 0:
                raise WebSearchError(
                    f"the search runtime did not start: {stderr.strip()[:500]}"
                )
            if not await self._wait_ready(port):
                logs, _, _ = await self._run(
                    profile, "logs", "--tail", "20", CONTAINER_NAME, timeout=20
                )
                raise WebSearchError(
                    "the search runtime started but never became ready: "
                    + logs.strip()[-400:]
                )
            self.record(digest=digest, port=port, state=WebSearchRuntimeState.READY)
            self._touch()
            self._schedule_idle_stop()
            return port

    async def _probe(self, port: int) -> bool:
        try:
            async with httpx.AsyncClient(timeout=3.0, trust_env=False) as client:
                response = await client.get(f"http://127.0.0.1:{port}/healthz")
        except httpx.HTTPError as exc:
            record_caught_exception(
                "runtime",
                "runtime.web_search.probe_failed",
                "The search runtime did not answer a readiness probe.",
                exc,
                stage="web_search",
            )
            return False
        # Older builds have no /healthz; answering HTTP at all proves liveness.
        return response.status_code < 500

    async def _wait_ready(self, port: int) -> bool:
        deadline = asyncio.get_running_loop().time() + READY_TIMEOUT_SECONDS
        while asyncio.get_running_loop().time() < deadline:
            if await self._probe(port):
                return True
            await asyncio.sleep(1.0)
        return False

    def _touch(self) -> None:
        self._last_used = asyncio.get_running_loop().time()

    def _schedule_idle_stop(self) -> None:
        if self._idle_task is not None and not self._idle_task.done():
            return
        self._idle_task = create_diagnostic_task(
            self._idle_loop(),
            feature="runtime",
            event_code="runtime.web_search.idle_loop_failed",
            failure_message="The search runtime idle watcher stopped unexpectedly.",
            name="nebula-search-idle",
        )

    async def _idle_loop(self) -> None:
        while True:
            await asyncio.sleep(60.0)
            idle = asyncio.get_running_loop().time() - self._last_used
            if idle < IDLE_STOP_SECONDS:
                continue
            try:
                await self.stop()
            except WebSearchError as exc:
                record_caught_exception(
                    "runtime",
                    "runtime.web_search.idle_stop_failed",
                    "The idle search runtime could not be stopped.",
                    exc,
                    stage="web_search",
                )
            return

    async def stop(self) -> None:
        profile = self._profile()
        await self._run(profile, "stop", "--time", "5", CONTAINER_NAME, timeout=30)
        self.record(state=WebSearchRuntimeState.STOPPED)

    async def remove(self) -> None:
        profile = self._profile()
        await self._run(profile, "rm", "--force", CONTAINER_NAME, timeout=30)
        self.record(state=WebSearchRuntimeState.ABSENT)

    def record(self, **changes: Any) -> None:
        settings = load_settings(self.store)
        if settings is None:
            self.store.create(WebSearchSettings(id=SETTINGS_ID, **changes))
            return
        self.store.update(
            WebSearchSettings,
            settings.id,
            changes,
            expected_revision=settings.revision,
        )

    # -- queries -----------------------------------------------------------

    async def search(
        self,
        query: str,
        *,
        count: int = DEFAULT_RESULTS,
        freshness: Freshness = "any",
    ) -> list[WebSearchResult]:
        port = await self.ensure_ready()
        self._touch()
        settings = load_settings(self.store)
        engines = settings.engines if settings else list(WebSearchEngine)[:3]
        parameters: dict[str, str] = {
            "q": query,
            "format": "json",
            "language": "en",
            "safesearch": "0",
            "engines": ",".join(engine.value for engine in engines),
        }
        if freshness != "any":
            parameters["time_range"] = _TIME_RANGE[freshness]
        try:
            async with httpx.AsyncClient(
                timeout=SEARCH_TIMEOUT_SECONDS, trust_env=False
            ) as client:
                response = await client.get(
                    f"http://127.0.0.1:{port}/search", params=parameters
                )
                response.raise_for_status()
                document = response.json()
        except httpx.HTTPError as exc:
            raise WebSearchError(f"the search runtime failed: {exc}") from exc
        except json.JSONDecodeError as exc:
            raise WebSearchError("the search runtime returned invalid JSON") from exc
        return normalize_results(document, count=count)

    async def check(self) -> WebSearchTest:
        """Run a fixed neutral query; never touches project data."""

        started = utc_now()
        try:
            results = await self.search("nebula security testing", count=3)
        except WebSearchError as exc:
            # diagnostic-expected: the failure is the test's reported result
            return WebSearchTest(tested_at=started, ok=False, error=str(exc)[:500])
        completed = utc_now()
        return WebSearchTest(
            tested_at=started,
            ok=bool(results),
            latency_ms=int((completed - started).total_seconds() * 1000),
            engines_answered=sorted(
                {item.engine for item in results if item.engine is not None}
            )[:32],
            error=None if results else "the runtime answered with no results",
        )


def normalize_results(document: Any, *, count: int) -> list[WebSearchResult]:
    """Bound, redact and rank the runtime's answer."""

    if not isinstance(document, dict):
        raise WebSearchError("the search runtime returned an unexpected payload")
    entries = document.get("results")
    if not isinstance(entries, list):
        return []
    results: list[WebSearchResult] = []
    seen: set[str] = set()
    for entry in entries:
        if len(results) >= min(count, MAX_RESULTS):
            break
        if not isinstance(entry, dict):
            continue
        url = str(entry.get("url") or "").strip()
        title = str(entry.get("title") or "").strip()
        if not url or not title or url in seen:
            continue
        if not url.lower().startswith(("http://", "https://")):
            continue
        seen.add(url)
        engines = entry.get("engines")
        engine = entry.get("engine") or (
            engines[0] if isinstance(engines, list) and engines else None
        )
        results.append(
            WebSearchResult(
                rank=len(results) + 1,
                title=redact_text(title)[:MAX_TITLE_CHARS],
                url=url[:500],
                snippet=redact_text(str(entry.get("content") or "").strip())[
                    :MAX_SNIPPET_CHARS
                ],
                engine=str(engine)[:40] if engine else None,
                published_at=(
                    str(entry["publishedDate"])[:40]
                    if entry.get("publishedDate")
                    else None
                ),
            )
        )
    return results


# -- scope disclosure guard ------------------------------------------------


def _scope_hosts(scope: ScopePolicy) -> list[str]:
    hosts: list[str] = []
    for domain in scope.allowed_domains:
        candidate = domain.lstrip("*.").strip().lower()
        label = candidate.split(".")[0] if candidate else ""
        if candidate and len(label) >= _DISCLOSURE_MIN_LABEL_CHARS:
            hosts.append(candidate)
    for url in scope.allowed_urls:
        match = re.match(r"^[a-z]+://([^/:?#]+)", url.strip().lower())
        if match:
            hosts.append(match.group(1))
    return sorted(set(hosts))


def scope_disclosure_conflict(query: str, scope: ScopePolicy) -> str | None:
    """Return the in-scope token a query would disclose, if any.

    Sending a client's hostname or address to upstream search engines is a
    disclosure the operator authorizes at project level, not something the
    model decides mid-turn.
    """

    if scope.web_search_discloses_scope:
        return None
    lowered = query.lower()
    for host in _scope_hosts(scope):
        # A leading dot is allowed so a subdomain of an in-scope domain still
        # counts; a leading word character or hyphen is not, so a longer
        # unrelated name such as "notacme-client.com" never trips the guard.
        if re.search(rf"(?<![\w-]){re.escape(host)}(?![\w-])", lowered):
            return host
    networks = []
    for entry in scope.allowed_cidrs:
        try:
            networks.append(ipaddress.ip_network(entry, strict=False))
        except ValueError as exc:
            record_caught_exception(
                "runtime",
                "runtime.web_search.invalid_scope_cidr",
                "A scope CIDR could not be parsed while checking a search query.",
                exc,
                stage="web_search",
            )
            continue
    if not networks:
        return None
    for token in re.findall(
        r"\b(?:\d{1,3}\.){3}\d{1,3}\b|\b[0-9a-f:]{3,}:[0-9a-f:]+\b", lowered
    ):
        try:
            address = ipaddress.ip_address(token)
        except ValueError:  # diagnostic-expected: most tokens are not addresses
            continue
        for network in networks:
            if address.version == network.version and address in network:
                return token
    return None


