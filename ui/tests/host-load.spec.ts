import {expect, test} from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";

test("host pressure settings apply live, queue durably and recover", async ({page, request}, info) => {
  expect(new URL(String(info.project.use.baseURL)).hostname).not.toMatch(/^(localhost$|127\.|\[?::1\]?$)/);
  const origin = `http://127.0.0.1:${new URL(String(info.project.use.baseURL)).port}`;
  const headers = {Authorization: "Bearer host-load-test-token"};
  const control = async (data: Record<string, unknown>) => {
    const response = await request.post(`${origin}/__host_fixture/load`, {headers, data});
    expect(response.ok(), await response.text()).toBeTruthy(); return response.json();
  };
  const read = async () => (await request.get(`${origin}/api/v1/host-pressure`, {headers})).json();
  const initialPolicy = await read();
  const reset = await request.put(`${origin}/api/v1/host-pressure`, {headers, data: {host_id: initialPolicy.host_id, expected_revision: initialPolicy.revision, thresholds: {cpu: .8, memory: .8, load: .8, io: .8}}});
  expect(reset.ok()).toBeTruthy();
  const fixture = await control({busy: true, cpu: 0.85, reset_calls: true});
  const pairing = await (await request.post(`${origin}/api/v1/auth/pairings`, {headers, data: {name: "Synthetic pressure device"}})).json();
  await page.goto(`/#pair=${encodeURIComponent(pairing.secret)}&code=${encodeURIComponent(pairing.confirmation_code)}`);
  await page.getByLabel("Device name").fill("Synthetic pressure device");
  await page.getByRole("button", {name: "Pair device", exact: true}).click();
  await expect(page.getByRole("button", {name: /Nebula Core (ready|degraded)/})).toBeVisible({timeout: 20000});
  const project = "capacity-" + info.project.name;
  const chat = "chat-" + info.project.name;
  const chatUrl = `/projects/${project}/workbench?view=chat&session=${chat}`;
  await page.goto(chatUrl);
  const composer = page.getByRole("textbox", {name: "Message the analyst assistant"});
  await composer.fill("Synthetic pressure first request");
  await page.getByRole("button", {name: "Send message", exact: true}).click();
  await expect(page.getByText(/Waiting for host pressure: CPU/).first()).toBeVisible({timeout: 20000});
  await page.reload();
  await expect(page.getByText(/Waiting for host pressure: CPU/).first()).toBeVisible({timeout: 20000});
  expect((await read()).concurrency).toMatchObject({provider_limit: 60, background_limit: 58, active: 0});

  await page.goto("/settings#setup-settings");
  const section = page.getByRole("region", {name: "Host pressure", exact: true});
  const cpu = section.getByLabel("CPU use threshold (%)", {exact: true});
  const save = section.getByRole("button", {name: "Save pressure thresholds", exact: true});
  await section.scrollIntoViewIfNeeded();
  await expect(cpu).toHaveValue("80");
  await expect(section.getByText("Provider limit: 60 · Background limit: 58")).toBeVisible();
  await cpu.fill("0"); await expect(save).toBeDisabled();
  await cpu.fill("90"); await save.click();
  await expect(save).toBeDisabled();
  await expect.poll(async () => (await read()).effective_thresholds.cpu).toBe(0.9);
  await page.reload(); await expect(cpu).toHaveValue("90");
  expect((await new AxeBuilder({page}).include("[aria-labelledby=host-pressure-title]").analyze()).violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  for (const element of await section.locator("input, button").all()) expect((await element.boundingBox())?.height).toBeGreaterThanOrEqual(44);
  await page.screenshot({path: info.outputPath("host-pressure-settings.png"), fullPage: true});
  await page.goto(chatUrl);
  await expect(page.getByText("Synthetic host capacity answer.", {exact: true}).first()).toBeVisible({timeout: 20000});
  expect((await control({busy: true})).calls).toBe(1);
  await composer.fill("Synthetic cancelled pressure request");
  await page.getByRole("button", {name: "Send message", exact: true}).click();
  await expect(page.getByText(/Waiting for host pressure: CPU/).first()).toBeVisible({timeout: 20000});
  await page.locator(".chat-composer").getByRole("button", {name: "Stop response", exact: true}).click();
  await expect(page.locator(".chat-composer").getByRole("button", {name: "Send message", exact: true})).toBeVisible();
  expect((await control({io: true})).calls).toBe(1);
  await composer.fill("Synthetic I/O pressure request");
  await page.getByRole("button", {name: "Send message", exact: true}).click();
  await expect(page.getByText(/Waiting for host pressure: I\/O/).first()).toBeVisible({timeout: 20000});
  await control({io_ratio: 0.79});
  await expect.poll(async () => (await control({io_ratio: 0.79})).calls).toBe(2);
  await expect.poll(async () => (await (await request.get(`${origin}/api/v1/chat/sessions/${chat}/pending-turn`, {headers})).json())).toBeNull();
  const evidence = {origin: info.project.use.baseURL, bundleSha256: fixture.bundle_sha256, profile: info.project.name, viewport: page.viewportSize(), observed: await read()};
  console.info("Host pressure acceptance", JSON.stringify(evidence));
  await info.attach("candidate-build", {body: JSON.stringify(evidence), contentType: "application/json"});
});
