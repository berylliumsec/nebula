import {createHash} from "node:crypto";
import {expect, test} from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";

test("memory budgets save, conflict, enforce a bounded allocation and survive reload", async ({page, request}, info) => {
  const origin = String(info.project.use.baseURL);
  const headers = {Authorization: "Bearer memory-budget-test-token"};
  const reset = await request.post(`${origin}/__memory_fixture/reset`, {headers}); expect(reset.ok()).toBeTruthy();
  const build = await reset.json();
  const index = await request.get(origin + "/index.html");
  expect(createHash("sha256").update(await index.body()).digest("hex")).toBe(build.index_sha256);
  const read = async () => (await request.get(`${origin}/api/v1/memory-budgets`, {headers})).json();
  const invitation = await request.post(`http://127.0.0.1:${new URL(origin).port}/api/v1/auth/pairings`, {headers, data: {name: "Synthetic memory device"}});
  expect(invitation.ok()).toBeTruthy(); const pairing = await invitation.json();
  await page.goto(`/#pair=${encodeURIComponent(pairing.secret)}&code=${encodeURIComponent(pairing.confirmation_code)}`);
  await page.getByLabel("Device name").fill("Synthetic memory device");
  await page.getByRole("button", {name: "Pair device", exact: true}).click();
  await expect(page.getByRole("heading", {name: "Pair this device", exact: true})).toBeHidden({timeout: 20000});
  await page.goto("/settings#memory-budget-settings");
  const section = page.getByRole("region", {name: "Memory budgets", exact: true});
  await section.scrollIntoViewIfNeeded();
  const ceiling = section.getByLabel(/Per job ceiling/);
  const save = section.getByRole("button", {name: "Save memory budgets"});
  await expect(ceiling).toHaveValue("2");
  const reserve = section.getByLabel(/Core and services reserve/);
  await expect(reserve).toHaveValue("3");
  await expect(reserve).toHaveAttribute("min", "2.25");
  await expect(section.getByText(/Resident runtimes reserve 0.25 GiB/)).toBeVisible();
  expect((await read()).minimum_core_reserve_bytes).toBe(2.25 * 1024 ** 3);
  await ceiling.fill("4"); await save.click();
  await expect(section.getByText(/Saved and read back/)).toBeVisible();
  expect((await read()).policy.default_job.max_bytes).toBe(4 * 1024 ** 3);
  await page.reload(); await expect(ceiling).toHaveValue("4");
  await ceiling.fill("3");
  const current = await read();
  expect((await request.put(`${origin}/api/v1/memory-budgets`, {headers, data: {expected_revision: current.revision, policy: {...current.policy, aggregate_bytes: 10 * 1024 ** 3}}})).ok()).toBeTruthy();
  await save.click(); await expect(section.getByRole("alert")).toContainText(/changed|409/);
  await expect(ceiling).toHaveValue("3");
  await section.getByRole("button", {name: "Reload memory budgets"}).click();
  await expect(ceiling).toHaveValue("4");
  await expect(section.getByLabel(/Total job budget/)).toHaveValue("10");
  await section.getByText("Enforcement support", {exact: true}).click();
  await section.getByRole("button", {name: "Check enforcement"}).click();
  await expect(section.getByText(/Runner support checked/)).toBeVisible();
  expect((await read()).capabilities.some((item: {kernel_enforced: boolean}) => item.kernel_enforced)).toBe(true);
  const work = request.post(`${origin}/__memory_fixture/allocation`, {headers, data: {oversized: true}});
  const health = await request.get(`${origin}/api/v1/health`, {headers}); expect(health.ok()).toBeTruthy();
  const response = await work; expect(response.ok()).toBeTruthy();
  const result = await response.json(); expect(result.outcome).toBe("memory_limit_exceeded");
  await section.getByRole("button", {name: "Reload memory budgets"}).click();
  const job = section.getByRole("listitem").filter({hasText: result.job_id});
  await expect(job).toContainText("memory_limit_exceeded");
  await expect(job).toContainText("retry explicitly");
  await page.reload(); await expect(job).toContainText("memory_limit_exceeded");
  expect((await read()).reserved_bytes).toBe(0);
  await section.scrollIntoViewIfNeeded();
  expect((await new AxeBuilder({page}).include("#memory-budget-settings").analyze()).violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  for (const element of await section.locator("input[type=number]:visible, button:visible").all()) expect((await element.boundingBox())?.height).toBeGreaterThanOrEqual(44);
  await ceiling.focus(); await expect(ceiling).toBeFocused();
  await page.screenshot({path: `/tmp/nebula-memory-${info.project.name}.png`, fullPage: true});
});
